{
	public const float Scale = 3.0f;

	// UI строится кодом и уменьшается в это число раз, чтобы хрустящие пиксельные шрифты
	// не мылились при масштабировании вьюпорта (960x540 -> 1080p через window override)
	public const float UiScale = 3.5f;
}
